<script setup>
import { reactive, computed } from 'vue'
import AltLayout from '@/layouts/AltLayout.vue'

const questions = [
  {
    q: 'Pour quel poste Monsieur Morales passe-t-il l\'entretien ?',
    options: ['Vendeur', 'Cuisinier', 'Professeur'],
    answer: 0,
  },
  {
    q: 'Où se trouve l\'entreprise ?',
    options: ['À Madrid, en Espagne', 'À Lausanne, en Suisse romande', 'À Paris, en France'],
    answer: 1,
  },
  {
    q: 'Combien d\'années d\'expérience a-t-il comme vendeur ?',
    options: ['Six mois', 'Cinq ans', 'Deux ans'],
    answer: 2,
  },
  {
    q: 'Quelles langues parle Monsieur Morales ?',
    options: ['Espagnol, français et un peu d\'anglais', 'Seulement espagnol', 'Allemand et italien'],
    answer: 0,
  },
  {
    q: 'Quand est-il disponible ?',
    options: ['Dès le mois prochain', 'L\'année prochaine', 'Il n\'est pas disponible'],
    answer: 0,
  },
  {
    q: 'Quand l\'entreprise va-t-elle donner une réponse ?',
    options: ['Demain', 'La semaine prochaine', 'Le mois prochain'],
    answer: 1,
  },
]

const picks = reactive(questions.map(() => null))

function pick(qi, oi) {
  if (picks[qi] !== null) return
  picks[qi] = oi
}

function optionClass(qi, oi) {
  if (picks[qi] === null) return ''
  if (oi === questions[qi].answer) return 'is-correct'
  if (oi === picks[qi]) return 'is-wrong'
  return 'is-neutral'
}

const allAnswered = computed(() => picks.every(p => p !== null))

const score = computed(() =>
  picks.reduce((n, p, qi) => n + (p === questions[qi].answer ? 1 : 0), 0)
)

function resetQuiz() {
  picks.forEach((_, i) => { picks[i] = null })
}
</script>

