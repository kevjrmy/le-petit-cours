              <td>le <strong>ci</strong>néma, dou<strong>ce</strong></td>
            </tr>
            <tr>
              <td>a, o, u</td><td><strong class="hl-blue">ç</strong></td><td><em>/s/</em></td>
              <td>fran<strong>ç</strong>ais, gar<strong>ç</strong>on, il a re<strong>ç</strong>u</td>
            </tr>
            <tr>
              <td>a, o, u</td><td><strong class="hl-blue">c</strong></td><td><em>/k/</em></td>
              <td>le <strong>ca</strong>fé, l'é<strong>co</strong>le, é<strong>cou</strong>ter</td>
            </tr>
          </tbody>
        </table>

        <div class="exception">
          <strong>Jamais de cédille devant e ni i.</strong> Le <em>c</em> y est déjà doux, la
          cédille n'aurait rien à faire&nbsp;: on écrit <em>ce</em>, <em>ci</em>,
          <em>cinéma</em> — et jamais <em class="hl-red">çe</em> ni <em class="hl-red">çi</em>.
        </div>

