      <article>
        <h2>5. La cédille</h2>
        <div class="rule">
          Le <strong>c</strong> se prononce <em>/s/</em> devant <strong>e</strong> et
          <strong>i</strong>, mais <em>/k/</em> devant <strong>a</strong>, <strong>o</strong>
          et <strong>u</strong>. La cédille sert à garder le son <em>/s/</em> devant ces
          trois voyelles-là.
        </div>

