          Le <strong class="hl-blue">passé composé</strong> s'utilise pour exprimer une action ponctuelle et terminée dans le passé.
          En espagnol, il correspond au <strong class="hl-blue">«&nbsp;pretérito perfecto compuesto&nbsp;»</strong> (<em>he hablado</em>) ou au <strong class="hl-blue">«&nbsp;pretérito indefinido&nbsp;»</strong> (<em>hablé</em>).
          <br><br>
          <strong class="hl-red">Attention !</strong> En espagnol, on utilise toujours l'auxiliaire <em>haber</em>. En français, on utilise l'auxiliaire <strong class="hl-blue">avoir</strong> ou <strong class="hl-blue">être</strong> selon le verbe.
        </div>
      </article>

