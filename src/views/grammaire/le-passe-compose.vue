        <h2>1. Le passé composé avec <em>avoir</em> (la majorité des verbes)</h2>
        <p class="method">
          Il se forme avec l'auxiliaire <strong class="hl-blue">avoir</strong> au présent + le <strong class="hl-blue">participe passé</strong> du verbe principal.
        </p>

        <p class="method-example">
          <strong>avoir</strong> (présent)
          <span class="arrow-inline" aria-hidden="true">+</span>
          <strong>participe passé</strong>
        </p>

