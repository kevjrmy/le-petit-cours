        <h3>Formation des participes passés (par terminaison)</h3>
        <div class="example">
          <strong>1<sup>er</sup> groupe (-er)</strong> → <strong>-é</strong> : parler → parlé, visiter → visité, manger → mangé.
        </div>
        <div class="example">
          <strong>2<sup>e</sup> groupe (-ir)</strong> → <strong>-i</strong> : finir → fini, choisir → choisi.
        </div>
        <div class="example">
          <strong>3<sup>e</sup> groupe (verbes en -dre)</strong> :
          <br>
          • Verbes en <em>-andre, -endre, -ondre, -erdre</em> → <strong>-u</strong> : vendre → <strong>vendu</strong>, attendre → <strong>attendu</strong>, répondre → <strong>répondu</strong>.
          <br>
          • Verbes de la famille de <em>prendre</em> (-prendre) → <strong>-pris</strong> : prendre → <strong>pris</strong>, apprendre → <strong>appris</strong>, comprendre → <strong>compris</strong>.
        </div>

        <h3>Autres participes passés fréquents (3<sup>e</sup> groupe)</h3>
        <div class="example">
          avoir → <strong>eu</strong> · être → <strong>été</strong> · faire → <strong>fait</strong> · voir → <strong>vu</strong> · pouvoir → <strong>pu</strong> · vouloir → <strong>voulu</strong> · écrire → <strong>écrit</strong> · mettre → <strong>mis</strong>.
        </div>
      </article>

