      <!-- ── Le partitif ─────────────────────────── -->
      <article>
        <h2>Du, de la, des&nbsp;: dire la quantité</h2>
        <p class="method">
          Devant un aliment qu'on ne compte pas, le français met un article qui veut dire
          «&nbsp;une certaine quantité de&nbsp;». Il change avec le genre du mot.
        </p>

        <table>
          <caption class="sr-only">Les formes de l'article partitif</caption>
          <thead>
            <tr><th>Devant</th><th>On écrit</th><th>Exemple</th><th>En espagnol</th></tr>
          </thead>
          <tbody>
            <tr>
              <td>un mot masculin</td><td><strong class="hl-blue">du</strong></td>
              <td>je mange <strong>du</strong> pain</td><td><em>como pan</em></td>
            </tr>
            <tr>
              <td>un mot féminin</td><td><strong class="hl-blue">de la</strong></td>
              <td>je mange <strong>de la</strong> viande</td><td><em>como carne</em></td>
            </tr>
            <tr>
              <td>une voyelle</td><td><strong class="hl-blue">de l'</strong></td>
              <td>je bois <strong>de l'</strong>eau</td><td><em>bebo agua</em></td>
            </tr>
            <tr>
              <td>un pluriel</td><td><strong class="hl-blue">des</strong></td>
              <td>j'achète <strong>des</strong> tomates</td><td><em>compro tomates</em></td>
            </tr>
          </tbody>
        </table>

        <div class="example">
          Le matin, je prends <strong class="hl-blue">du</strong> café et
          <strong class="hl-blue">des</strong> tartines.
          <span class="note">(Por la mañana tomo café y tostadas)</span>
        </div>

        <div class="exception">
          <strong>À la forme négative, tout devient <span class="hl-red">de</span>.</strong>
          <span class="sep">·</span>
          Je mange <em>de la</em> viande <span class="arrow-inline" aria-hidden="true">→</span>
          je ne mange <strong class="hl-red">pas de</strong> viande.
          <span class="sep">·</span>
          Je bois <em>du</em> vin <span class="arrow-inline" aria-hidden="true">→</span>
          je ne bois <strong class="hl-red">pas de</strong> vin.
        </div>

        <p class="method">
          Après une quantité précise, c'est <strong class="hl-blue">de</strong> tout seul —
          jamais <em>du</em>, <em>de la</em> ni <em>des</em>.
        </p>

